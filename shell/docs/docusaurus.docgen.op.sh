#!/usr/bin/env bash

: <<'DOC'
Docusaurus, the first docs system of the docgen kind (docgen.sh says what
the roles mean): one markdown page per module at the module's path with
.sh as .md, and the index at README.md, which Docusaurus takes as the
landing page of the folder its sidebar is generated from. A page and the
index are rendered by the two awk programs under docusaurus/, which read
the tree and nothing else. A page opens on front matter Docusaurus reads:
its title, and, when the source is given, custom_edit_url, the module's
source file under it, which the page's edit link opens. The text of a doc
is written as CommonMark, as prose.awk under docusaurus/ says: a
placeholder such as <name> in a code span, and an indented example in a
fenced code block.

A snapshot is Docusaurus's own versioning layout for a docs plugin
instance whose id is the project's: the pages under
<project>_versioned_docs/version-<version>/, one autogenerated sidebar in
<project>_versioned_sidebars/version-<version>-sidebars.json, and the
version at the front of <project>_versions.json, once.
DOC

# CONST: The directory of the awk programs.
__docs__docusaurus__PROGRAMS="$SHELL_DOCS_DIR/shell/docs/docusaurus"

# CONST: The page renderer, an awk program over one module's tree.
__docs__docusaurus__PAGE="$__docs__docusaurus__PROGRAMS/page.awk"

# CONST: The index renderer, an awk program over the list of every module's tree.
__docs__docusaurus__INDEX="$__docs__docusaurus__PROGRAMS/index.awk"

# CONST: The awk program that prints the trees in tree files as one JSON list, which the index renderer reads.
__docs__docusaurus__TREES="$__docs__docusaurus__PROGRAMS/trees.awk"

# CONST: The awk library that writes a doc's text as CommonMark, which both renderers are loaded after.
__docs__docusaurus__PROSE="$__docs__docusaurus__PROGRAMS/prose.awk"

# CONST: The awk library that reads the nodes of a tree, which both renderers are loaded after.
__docs__docusaurus__NODES="$SHELL_DOCS_DIR/shell/docs/nodes.awk"

# CONST: The awk library that reads one line of a doc's text, which prose.awk is loaded after.
__docs__docusaurus__DOC_TEXT="$SHELL_DOCS_DIR/shell/docs/doc_text.awk"

@docgen.docusaurus() {
  @summary() {
    println "Markdown pages for a Docusaurus docs instance, one per module, with a README index as the landing page."
  }

  @needs() {
    @arr awk
  }

  @page() {
    __docusaurus_page__tree="$(cat "$1")" || return 1
    __docs__docusaurus__render "$__docs__docusaurus__PAGE" "$__docusaurus_page__tree" "${2:-}"
  }

  @index() {
    __docusaurus_index__trees="$(awk -f "$__docs__docusaurus__TREES" "$@")" || return 1
    __docs__docusaurus__render "$__docs__docusaurus__INDEX" "$__docusaurus_index__trees" ''
  }

  @page_path() {
    println "${1%.sh}.md"
  }

  @index_path() {
    println "README.md"
  }

  @snapshot() {
    __docs__docusaurus__write_pages "$1" "$2" "$3" "$4"
    __docs__docusaurus__write_sidebar "$2" "$3" "$4"
    __docs__docusaurus__write_versions "$2" "$3" "$4"
  }

  @has_version() {
    @succeeds [ -d "$(__docs__docusaurus__version_dir "$1" "$2" "$3")" ]
  }
}

: <<'FUN'
Prints what the renderer <program> writes for <trees>, the tree of one
module or the list of every module's, as Markdown. <source> is the URL
the module's source files are at for the version rendered, or nothing.

args:
  $1  The renderer, an awk program
  $2  The trees, as JSON
  $3  The source
FUN
__docs__docusaurus__render() {
  @run_awk __docs__docusaurus__render__page \
    "$1" \
    "$2" \
    --arg source "$3" \
    --load "$__docs__docusaurus__NODES" \
    --load "$__docs__docusaurus__DOC_TEXT" \
    --load "$__docs__docusaurus__PROSE" \
    || return 1
  println "$__docs__docusaurus__render__page"
}

: <<'FUN'
Prints the directory the pages of the version <version> of the project
<project> live in, under the site checkout at <site>.

  __docs__docusaurus__version_dir /site strata main  ->  /site/strata_versioned_docs/version-main
FUN
__docs__docusaurus__version_dir() {
  println "$1/${2}_versioned_docs/version-$3"
}

: <<'FUN'
Copies the pages under <pages> into the directory of the version <version>
of the project <project> under the site checkout at <site>, in place of
what that directory contained.

args:
  $1  The pages
  $2  The site
  $3  The project
  $4  The version
FUN
__docs__docusaurus__write_pages() {
  __docs__docusaurus__write_pages__dir="$(__docs__docusaurus__version_dir "$2" "$3" "$4")"
  rm -rf "${__docs__docusaurus__write_pages__dir:?}"
  mkdir -p "$__docs__docusaurus__write_pages__dir"
  cp -R "$1/." "$__docs__docusaurus__write_pages__dir/"
}

: <<'FUN'
Writes the sidebar file of the version <version> of the project <project>
under the site checkout at <site>: one autogenerated sidebar over the
version's directory, with its README as the landing page.
FUN
__docs__docusaurus__write_sidebar() {
  mkdir -p "$1/${2}_versioned_sidebars"
  @dump "$(@obj '.docs' "$(@arr "$(@obj '.type' autogenerated '.dirName' .)")")" \
    > "$1/${2}_versioned_sidebars/version-$3-sidebars.json"
}

: <<'FUN'
Puts the version <version> at the front of the versions list of the
project <project> under the site checkout at <site>, newest first, unless
the list already contains it. A project with no list yet gets one.
FUN
__docs__docusaurus__write_versions() {
  __docs__docusaurus__write_versions__file="$1/${2}_versions.json"
  if [ ! -f "$__docs__docusaurus__write_versions__file" ]; then
    @dump "$(@arr)" > "$__docs__docusaurus__write_versions__file"
  fi
  __docs__docusaurus__write_versions__list="$(cat "$__docs__docusaurus__write_versions__file")"
  if ! @is_true "$(@any __docs__docusaurus__is_version "$__docs__docusaurus__write_versions__list" "$3")"; then
    __docs__docusaurus__write_versions__list="$(@concat "$(@arr "$3")" "$__docs__docusaurus__write_versions__list")"
  fi
  @dump "$__docs__docusaurus__write_versions__list" > "$__docs__docusaurus__write_versions__file"
}

: <<'FUN'
Succeeds when the element of a versions list is the version <version>: the
callback @any runs over the list.

args:
  $1  The element, a wrapped string
  $2  The version
FUN
__docs__docusaurus__is_version() {
  [ "$(@unwrap "$1")" = "$2" ]
}
